interface LanguageCtx {
  lang: LanguageCode;
  setLang: (l: LanguageCode) => void;
  speechCode: string;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageCtx>({
  lang: "en",
  setLang: () => {},
  speechCode: "en-IN",
  t: (k) => k,
});

const STORAGE_KEY = "civic-guide-language";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LanguageCode>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && LANGUAGES.some((l) => l.code === saved)) return saved as LanguageCode;
    } catch {
      /* ignore */
    }
    return "en";
  });

  const setLang = (l: LanguageCode) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<LanguageCtx>(() => {
    const dict: Dict = { ...en, ...(lang !== "en" ? overrides[lang] : {}) };
    return {
      lang,
      setLang,
      speechCode: LANGUAGES.find((l) => l.code === lang)?.speechCode ?? "en-IN",
      t: (key: string) => dict[key] ?? en[key] ?? key,
    };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}

export function LanguageSelector({ compact = false }: { compact?: boolean }) {
  const { lang, setLang } = useLanguage();
  return (
    <select
      aria-label="Language"
      value={lang}
      onChange={(e) => setLang(e.target.value as LanguageCode)}
      className={`type-label rounded-md border border-border bg-card px-2 py-1.5 text-[11px] text-foreground shadow-sm focus:outline-none focus:ring-2 focus:ring-ring ${
        compact ? "" : "min-w-[8.5rem]"
      }`}
    >
      {LANGUAGES.map((l) => (
        <option key={l.code} value={l.code}>
          {l.native}
        </option>
      ))}
    </select>
  );
}
